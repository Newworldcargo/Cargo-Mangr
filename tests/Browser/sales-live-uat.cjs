const {chromium, expect}=require(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const assert=require('assert/strict');
const {spawnSync}=require('child_process');

(async()=>{
 const browser=await chromium.launch({args:['--no-sandbox']});
 const base=process.env.NWC_SALES_TEST_URL;
 assert(base?.startsWith('http://127.0.0.1:'));
 try {
  for(const type of ['invoices','quotations']){
   const width=type==='invoices'?1440:390;
   const page=await browser.newPage({viewport:{width,height:1000}});
   const pageErrors=[];
   page.on('pageerror',error=>pageErrors.push(error.stack));
   page.on('response',async response=>{if(response.url().endsWith('/preview')&&response.status()!==200)console.error('Preview error:',response.status(),await response.text());});
   await page.route('**/*',route=>new URL(route.request().url()).origin===base?route.continue():route.abort());
   page.on('dialog',dialog=>dialog.accept());
   const opening=await page.goto(`${base}/admin/sales/${type}/create`);
   assert.equal(opening.status(),200,(await page.locator('body').innerText()).slice(0,3000));
   await page.locator('#branch').selectOption({label:'Test Lusaka'});
   const total=page.locator('[data-total="total_minor"]');
   const field=(name,row=0)=>page.locator('#lines .sales-service-line').nth(row).locator(`[name$="[${name}]"]`);
   await field('description').fill('Air freight');
   await field('quantity').fill('10');
   await field('unit_price').fill('8.50');
   await expect(total,await page.locator('#totals-status').innerText()).toHaveText('ZMW 85.00');
   await expect(page.locator('#totals-status')).toContainText('Estimate only');
   await page.locator('.invoice-line-options summary').first().click();
   await field('tax_id').selectOption({label:'Non-VAT (0%)'});
   await page.locator('.invoice-line-options summary').first().click();
   await page.locator('#add-line').click();
   await expect(total).toHaveText('ZMW 85.00');
   await field('description',1).fill('Handling');
   await field('unit_price',1).fill('15');
   await page.locator('.invoice-line-options summary').nth(1).click();
   await field('tax_id',1).selectOption({label:'Non-VAT (0%)'});
   await expect(total).toHaveText('ZMW 100.00');
   await field('quantity').fill('15');
   await expect(total).toHaveText('ZMW 142.50');
   await expect(page.locator('.invoice-line-amount').first()).toHaveText('ZMW 127.50');
   await field('unit_price').fill('10');
   await expect(total).toHaveText('ZMW 165.00');
   await page.locator('.invoice-line-options summary').first().click();
   await field('discount').fill('5');
   await expect(total).toHaveText('ZMW 160.00');
   await field('tax_id').selectOption({label:'Test VAT (16%)'});
   await expect(total).toHaveText('ZMW 183.20');
   await field('tax_mode').selectOption('inclusive');
   await expect(total).toHaveText('ZMW 160.00');
   await field('tax_id').selectOption({label:'Non-VAT (0%)'});
   await field('discount').fill('0');
   await field('quantity').fill('0.125');
   await expect(total).toHaveText('ZMW 16.25');
   await field('unit_price').fill('0');
   await expect(total).toHaveText('ZMW 15.00');
   await field('quantity').fill('0');
   await expect(total).toHaveText('-');
   await expect(field('quantity')).toHaveAttribute('aria-invalid','true');
   await field('quantity').fill('10000');
   await field('unit_price').fill('1000');
   await expect(total).toHaveText('ZMW 10,000,015.00');
   await field('quantity').fill('2');
   await field('unit_price').fill('8.50');
   await expect(total).toHaveText('ZMW 32.00');
   await field('unit_price').press('Tab');
   await field('unit_price').focus();
   await field('unit_price').fill('9');
   await field('unit_price').press('Escape');
   await expect(field('unit_price')).toHaveValue('8.50');
   await expect(total).toHaveText('ZMW 32.00');
   await field('quantity').fill('3');
   await field('quantity').press('Enter');
   await expect(total).toHaveText('ZMW 40.50');
   assert(page.url().endsWith('/create'),'Enter must not save the draft');
   await page.locator('[data-remove]').last().click();
   await expect(total).toHaveText('ZMW 25.50');
   await page.locator('#add-line').click();
   await field('description',1).fill('Replacement charge');
   await field('unit_price',1).fill('20');
   if(!await field('tax_id',1).isVisible())await page.locator('.invoice-line-options summary').nth(1).click();
   await field('tax_id',1).selectOption({label:'Non-VAT (0%)'});
   await expect(total).toHaveText('ZMW 45.50');
   await page.locator('[data-remove]').first().click();
   await expect(total).toHaveText('ZMW 20.00');
   // Exercise sparse original field indices after deletion, and rapid edits.
   await field('quantity').fill('4');
   await field('quantity').fill('5');
   await field('quantity').fill('6');
   await expect(total).toHaveText('ZMW 120.00');
   const serviceSearch=page.getByRole('searchbox',{name:'Search services'});
   await serviceSearch.fill('Test air');
   await page.getByRole('button',{name:'Test air freight',exact:true}).click();
   await expect(total).toHaveText('ZMW 51.00');
   await expect(field('unit')).toHaveValue('kg');
   await serviceSearch.fill('Test sea');
   await page.getByRole('button',{name:'Test sea freight',exact:true}).click();
   await field('quantity').fill('0.5');
   await expect(total).toHaveText('ZMW 50.00');
   await expect(field('unit_price')).toHaveAttribute('readonly','');
   await expect(field('unit')).toHaveValue('cbm');
   await field('quantity').fill('2');
   await expect(total).toHaveText('ZMW 160.00');
   await serviceSearch.fill('Test air');
   await page.getByRole('button',{name:'Test air freight',exact:true}).click();
   await field('quantity').fill('6');
   await expect(total).toHaveText('ZMW 51.00');
   await page.context().setOffline(true);
   await field('unit_price').fill('21');
   await expect(page.locator('#totals-status')).toContainText('Your edits are still here');
   await expect(field('unit_price')).toHaveValue('21');
   await expect(total).toHaveText('-');
   await page.context().setOffline(false);
   await page.getByRole('button',{name:'Retry',exact:true}).click();
   await expect(total).toHaveText('ZMW 126.00');
   await page.locator('#customer-search').fill('Test Customer');
   await page.getByRole('button',{name:'Test Customer customer@test.example',exact:true}).click();
   const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,scrollX,
    content:document.querySelector('.content-wrapper').getBoundingClientRect().toJSON(),
    document:document.querySelector('.compact-document').getBoundingClientRect().toJSON(),
    overflowing:[...document.querySelectorAll('body *')].filter(node=>node.getBoundingClientRect().right>innerWidth+1&&getComputedStyle(node).position!=='fixed').slice(0,12).map(node=>({tag:node.tagName,id:node.id,classes:node.className,width:node.getBoundingClientRect().width}))}));
   assert(layout.scrollWidth<=width+1,JSON.stringify(layout));
   if(width>=992)assert(layout.content.x>=240,JSON.stringify(layout));
   assert(layout.document.x>=layout.content.x,JSON.stringify(layout));
   await page.evaluate(()=>window.scrollTo(0,0));
   await page.screenshot({path:`/tmp/nwc-sales-real-${type}.png`});
   await page.context().setOffline(true);
   await page.locator('button[form="sales-document-editor"]').click();
   await expect(page.locator('#save-status')).toContainText('Your edits are still here');
   await expect(field('unit_price')).toHaveValue('21');
   await page.context().setOffline(false);
   // Persist once but lose the response; retry must not create a second document.
   await page.route(`${base}/admin/sales/${type}`,async route=>{await route.fetch();await route.abort();},{times:1});
   await page.locator('button[form="sales-document-editor"]').click();
   await expect(page.locator('#save-status')).toContainText('Your edits are still here');
   await page.locator('button[form="sales-document-editor"]').click();
   await expect(page).toHaveURL(new RegExp(`/sales/${type}/\\d+$`));
   const savedUrl=page.url();
   await expect(page.locator('.sales-grand').last()).toContainText('126.00');
   await page.goto(savedUrl+'/edit');
   await expect(total).toHaveText('ZMW 126.00');
   await expect(field('quantity')).toHaveValue('6.000');
   await field('quantity').fill('7');
   await expect(total).toHaveText('ZMW 147.00');
   await page.locator('button[form="sales-document-editor"]').click();
   await expect(page).toHaveURL(savedUrl);
   await page.goto(savedUrl+'/print');
   await expect(page.locator('.sales-grand').last()).toContainText('147.00');
   const pdf=await page.request.get(savedUrl+'/download');
   assert.equal(pdf.status(),200);
   const bytes=await pdf.body();
   assert(bytes.subarray(0,4).toString()==='%PDF');
   const extracted=spawnSync('gs',['-q','-dSAFER','-dBATCH','-dNOPAUSE','-sDEVICE=txtwrite','-sOutputFile=-','-'],{input:bytes});
   assert.equal(extracted.status,0,extracted.stderr?.toString());
   assert.match(extracted.stdout.toString(),/147\.00/,'PDF must contain the saved total');
   assert.deepEqual(pageErrors,[],'No page scripts should throw errors');
   console.log(JSON.stringify({type,width,realBackend:true,passed:true,savedTotal:'147.00'}));
   await page.close();
  }
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
